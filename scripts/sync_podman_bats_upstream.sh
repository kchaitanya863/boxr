#!/usr/bin/env bash
# Copy upstream Podman test/system BATS (+ helpers) into the boxr tree and refresh manifest-all.txt.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PODMAN_TESTS_REPO="${PODMAN_TESTS_REPO:-https://github.com/podman-container-tools/podman.git}"
PODMAN_TESTS_REF="${PODMAN_TESTS_REF:-main}"
CACHE_DIR="${PODMAN_BATS_CACHE:-$REPO_ROOT/.cache/podman-bats}"
SRC_DIR="$CACHE_DIR/podman"
DEST="$REPO_ROOT/tests/podman_bats/upstream"
MANIFEST_ALL="$REPO_ROOT/tests/podman_bats/manifest-all.txt"

mkdir -p "$CACHE_DIR"

if [[ ! -d "$SRC_DIR/.git" ]]; then
  git clone --depth 1 --branch "$PODMAN_TESTS_REF" "$PODMAN_TESTS_REPO" "$SRC_DIR"
else
  git -C "$SRC_DIR" fetch --depth 1 origin "$PODMAN_TESTS_REF" 2>/dev/null || true
  git -C "$SRC_DIR" checkout -q FETCH_HEAD 2>/dev/null || git -C "$SRC_DIR" pull -q --ff-only 2>/dev/null || true
fi

SYSTEM="$SRC_DIR/test/system"
if [[ ! -d "$SYSTEM" ]]; then
  echo "missing $SYSTEM after clone" >&2
  exit 1
fi

commit="$(git -C "$SRC_DIR" rev-parse HEAD)"
mkdir -p "$DEST"

rsync -a --delete \
  --include='*.bats' \
  --include='helpers*.bash' \
  --include='setup_suite.bash' \
  --include='build-testimage' \
  --include='build-systemd-image' \
  --exclude='*' \
  "$SYSTEM/" "$DEST/"

UPSTREAM_DEST="$REPO_ROOT/tests/podman_upstream"
mkdir -p "$UPSTREAM_DEST"/{e2e,apiv2,compose,python,farm}
rsync -a --delete --exclude='e2e.test' --exclude='*.tmp' "$SRC_DIR/test/e2e/" "$UPSTREAM_DEST/e2e/"
rsync -a --delete --exclude='*.tmp' "$SRC_DIR/test/apiv2/" "$UPSTREAM_DEST/apiv2/"
rsync -a --delete --exclude='*.tmp' "$SRC_DIR/test/compose/" "$UPSTREAM_DEST/compose/"
rsync -a --delete --exclude='*.tmp' "$SRC_DIR/test/python/" "$UPSTREAM_DEST/python/"
rsync -a --delete --exclude='*.tmp' "$SRC_DIR/test/farm/" "$UPSTREAM_DEST/farm/"

cat >"$DEST/UPSTREAM.json" <<EOF
{
  "repository": "$PODMAN_TESTS_REPO",
  "ref": "$PODMAN_TESTS_REF",
  "commit": "$commit",
  "synced_at": "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
  "path_in_repo": "test/system"
}
EOF

{
  echo '# Full upstream Podman test/system catalog (auto-generated by scripts/sync_podman_bats_upstream.sh).'
  echo '# Curated passing subset: manifest.txt'
  echo '# Probe one file: MANIFEST=/tmp/one.txt ./scripts/run_podman_bats_conformance.sh'
  for f in "$DEST"/*.bats; do
    base="$(basename "$f" .bats)"
    [[ "$base" == '000-TEMPLATE' ]] && continue
    echo "$base"
  done | sort
} >"$MANIFEST_ALL"

count="$(grep -cve '^#' -e '^[[:space:]]*$' "$MANIFEST_ALL" || true)"
echo "Synced $count BATS files + helpers to $DEST (commit ${commit:0:12})"
